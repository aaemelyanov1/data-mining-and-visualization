# РАСХОЖДЕНИЕ 5.5 (исправлено): было .str.contains('~~||~~') — и это главная ошибка всего скрипта.
# Дело в том, что .str.contains() по умолчанию трактует образец как РЕГУЛЯРНОЕ ВЫРАЖЕНИЕ,
# где | — метасимвол «альтернатива». Шаблон '~~||~~' раскладывается как '~~' ИЛИ '' ИЛИ '~~'.
# Пустая альтернатива совпадает с пустой строкой, то есть с любой позицией в строке,
# поэтому условие всегда истинно и доля всегда равна 100 %. Правильный ответ — 8,6 %.
